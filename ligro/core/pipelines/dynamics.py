"""NVT -> NPT -> production MD pipeline executed through BioExcel blocks.

The pipeline consumes MDP files generated by the existing LiGRO UI and
coordinates each GROMACS operation through the Runner adapter. No shell
scripts or shell command strings are involved.
"""
import os
from dataclasses import dataclass

from ligro.core.io.topology import pack_topology


@dataclass
class DynamicsParams:
    topology: str = "trp.top"
    topology_archive: str = "trp.zip"
    nvt_mdp: str = "nvt.mdp"
    npt_mdp: str = "npt.mdp"
    md_mdp: str = "md.mdp"
    nvt_start: str = "em.gro"
    trajectory: bool = True
    run_production: bool = True


class MolecularDynamics:
    def __init__(self, params=None):
        self.params = params or DynamicsParams()

    def plan(self):
        return ["prepare_topology", "nvt_grompp", "nvt_mdrun",
                "npt_grompp", "npt_mdrun", "md_grompp", "md_mdrun",
                "validate_outputs"]

    @staticmethod
    def _require(path, description):
        if not os.path.isfile(path):
            raise RuntimeError("{} was not produced: {}".format(description, path))

    def run(self, workdir, runner):
        workdir = os.path.abspath(workdir)
        p = self.params
        required = (p.nvt_mdp, p.npt_mdp, p.md_mdp, p.nvt_start, p.topology)
        for name in required:
            self._require(os.path.join(workdir, name), "required input")

        archive = pack_topology(workdir, top_name=p.topology,
                                zip_name="trp_runtime.zip",
                                base_zip=p.topology_archive)

        def call(label, fn):
            try:
                return fn()
            except Exception as exc:
                raise RuntimeError("dynamics step '{}' failed: {}".format(label, exc)) from exc

        nvt_tpr = os.path.join(workdir, "nvt.tpr")
        nvt_gro = os.path.join(workdir, "nvt.gro")
        npt_tpr = os.path.join(workdir, "npt.tpr")
        npt_gro = os.path.join(workdir, "npt.gro")
        md_tpr = os.path.join(workdir, "md.tpr")

        call("nvt_grompp", lambda: runner.grompp(
            os.path.join(workdir, p.nvt_mdp), os.path.join(workdir, p.nvt_start),
            archive, nvt_tpr, ref=os.path.join(workdir, "em.gro")))
        call("nvt_mdrun", lambda: runner.mdrun(nvt_tpr, os.path.join(workdir, "nvt")))
        self._require(nvt_gro, "NVT coordinates")

        call("npt_grompp", lambda: runner.grompp(
            os.path.join(workdir, p.npt_mdp), nvt_gro, archive, npt_tpr,
            ref=nvt_gro))
        call("npt_mdrun", lambda: runner.mdrun(npt_tpr, os.path.join(workdir, "npt")))
        self._require(npt_gro, "NPT coordinates")

        call("md_grompp", lambda: runner.grompp(
            os.path.join(workdir, p.md_mdp), npt_gro, archive, md_tpr,
            ref=npt_gro))
        if p.run_production:
            call("md_mdrun", lambda: runner.mdrun(
                md_tpr, os.path.join(workdir, "md"), write_xtc=p.trajectory,
                write_cpt=True))
            for name in ("md.gro", "md.edr"):
                self._require(os.path.join(workdir, name), "production MD output")
            if p.trajectory:
                self._require(os.path.join(workdir, "md.xtc"), "production trajectory")
        self._require(md_tpr, "production run input")
        return {
            "tpr": md_tpr,
            "gro": os.path.join(workdir, "md.gro") if p.run_production else None,
            "edr": os.path.join(workdir, "md.edr") if p.run_production else None,
            "xtc": os.path.join(workdir, "md.xtc") if p.run_production and p.trajectory else None,
        }
